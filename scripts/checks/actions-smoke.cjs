'use strict';
// 使用隔离数据验证分类切换和真实自绘子菜单，不写入用户桌宠数据。
const {_electron:electron}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const programs=require('../../src/shared/special-actions.js');
const createPetMenuDriver=require('./pet-menu-driver.cjs');
const root=path.resolve(__dirname, '../..');
(async()=>{
  const dir=fs.mkdtempSync('/tmp/whale-actions-');
  const app=await electron.launch({executablePath:require('electron'),args:[root],env:{...process.env,WHALE_DATA_DIR:dir}});
  try {
    await app.firstWindow();
    let panel;
    for(let i=0;i<100;i++){
      panel=app.windows().find(page=>page.url().endsWith('/index.html'));
      if(panel)break;
      await new Promise(resolve=>setTimeout(resolve,100));
    }
    assert.ok(panel);
    assert.equal(await panel.getByText('鲸鱼娘的小角落',{exact:true}).count(),0);
    const errors=[];panel.on('pageerror',e=>errors.push(e.message));
    await panel.waitForSelector('#tab-daily');
    const tabs=['tab-daily','tab-emotions','tab-programs'];
    const counts=[8,3,8];
    for(let i=0;i<tabs.length;i++){
      await panel.locator('#'+tabs[i]).click();
      assert.equal(await panel.locator('[role="tabpanel"]:visible').count(),1);
      assert.equal(await panel.locator('[role="tabpanel"]:visible button').count(),counts[i]);
      assert.equal(await panel.locator('#'+tabs[i]).getAttribute('aria-selected'),'true');
      const layout=await panel.locator('[role="tabpanel"]:visible').evaluate(el=>{
        const boxes=[...el.children].map(b=>b.getBoundingClientRect());
        return {columns:getComputedStyle(el).gridTemplateColumns.split(' ').length,fits:boxes.every(b=>b.left>=el.getBoundingClientRect().left&&b.right<=el.getBoundingClientRect().right+1)};
      });
      assert.ok(layout.columns<=4&&layout.columns>=3&&layout.fits);
    }
    const before=await panel.evaluate(()=>window.whale.snapshot());
    await panel.locator('#tab-programs').press('ArrowRight');
    assert.equal(await panel.locator('#tab-daily').getAttribute('aria-selected'),'true');
    await panel.locator('#tab-daily').press('End');
    assert.equal(await panel.locator('#tab-programs').getAttribute('aria-selected'),'true');
    const after=await panel.evaluate(()=>window.whale.snapshot());
    assert.equal(after.revision,before.revision,'分类切换不能触发动作');
    assert.deepEqual(after.nurture,before.nurture);
    fs.mkdirSync(path.join(root,'out'),{recursive:true});
    await panel.locator('.action-library').evaluate(el=>el.scrollIntoView({block:'center'}));
    const clip=await panel.locator('.action-library').boundingBox();
    await panel.screenshot({path:path.join(root,'out/action-categories.png'),clip});
    await panel.locator('#tab-emotions').click();
    await panel.locator('[data-demo="happy"]').click();
    assert.equal(await panel.locator('#state-label').textContent(),'演示 · 开心');
    const pet=app.windows().find(page=>page.url().endsWith('/pet.html'));
    const petBeforeMenu=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('/pet.html')).getBounds());
    const driver=createPetMenuDriver(app,pet);
    let menu=await driver.open({x:20,y:30});
    menu.on('pageerror',e=>errors.push(e.message));
    const initialMenu=await driver.geometry(),position=initialMenu.panels[0];
    await driver.open({x:130,y:140});
    assert.deepEqual((await driver.geometry()).panels[0],position,'clicking another part of the pet must not move the menu');
    const geometry=()=>app.evaluate(({BrowserWindow,screen})=>{const win=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('/pet.html'));return {bounds:win.getContentBounds(),area:screen.getDisplayMatching(win.getBounds()).workArea};});
    const edge=await geometry(),edgeArt=await pet.locator('#pet-art').boundingBox();
    assert.ok(position.x<edge.bounds.x+edgeArt.x,'near the right screen edge the menu must dock on the left');
    assert.ok(position.x>=edge.area.x&&position.y>=edge.area.y&&position.y+position.height<=edge.area.y+edge.area.height,'measured menu must fit within the work area');
    assert.deepEqual(edge.bounds,petBeforeMenu,'opening the menu must not resize or move the pet');
    const labels=()=>menu.getByRole('menu',{name:'桌宠菜单',exact:true}).getByRole('menuitem').allTextContents();
    const text=await labels();
    assert.deepEqual(text.map(value=>value.replace(/^[♡✦⌂◌↻×]/u,'').replace(/›$/u,'')),['互动表情','小节目','打开小屋','隐藏桌宠','重启','退出']);
    await menu.getByRole('menuitem',{name:'互动表情'}).hover();
    assert.deepEqual(await menu.getByRole('menu',{name:'互动表情',exact:true}).getByRole('menuitem').allTextContents(),['喂饭','摸头','开心','生气']);
    await menu.getByRole('menuitem',{name:'小节目',exact:true}).hover();
    assert.equal(await menu.evaluate(()=>document.activeElement.dataset.id),'programs','pointer selection must replace the previous keyboard focus');
    assert.deepEqual(await menu.getByRole('menu',{name:'小节目',exact:true}).getByRole('menuitem').allTextContents(),Object.values(programs).map(p=>p.label));
    assert.deepEqual((await driver.geometry()).panels[0],position,'opening a submenu must preserve the main menu screen position');
    assert.deepEqual((await driver.geometry()).bounds,initialMenu.bounds,'hovering between different-height submenus must not move or resize their host');
    await menu.getByRole('menuitem',{name:'舞狮头',exact:true}).hover();
    assert.equal(await menu.getByRole('menu',{name:'小节目',exact:true}).count(),1,'moving through the gap must retain the submenu');
    await menu.keyboard.press('Escape');
    assert.equal((await driver.geometry()).visible,false);
    await app.evaluate(({BrowserWindow,screen})=>{const win=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('/pet.html')),area=screen.getPrimaryDisplay().workArea;win.setPosition(area.x+20,area.y+20);});
    await driver.open({x:20,y:30});
    const moved=(await driver.geometry()).panels[0],movedGeometry=await geometry(),movedArt=await pet.locator('#pet-art').boundingBox();
    assert.ok(moved.x>movedGeometry.bounds.x+movedArt.x+movedArt.width,'with space available the menu must dock on the right');
    await driver.open({x:130,y:140});
    assert.deepEqual((await driver.geometry()).panels[0],moved,'fixed anchor must follow the moved pet instead of the mouse');
    await menu.keyboard.press('ArrowDown');
    await menu.keyboard.press('ArrowRight');
    await menu.getByRole('menuitem',{name:'舞狮头',exact:true}).waitFor();
    let layout=await driver.geometry();
    assert.ok(layout.panels[1].x>=layout.panels[0].x+layout.panels[0].width,'submenu must attach to the right when space is available');
    await menu.screenshot({path:path.join(root,'out/pet-menu.png')});
    await menu.keyboard.press('ArrowLeft');
    assert.equal(await menu.getByRole('menu').count(),1);
    await menu.keyboard.press('ArrowRight');
    await menu.keyboard.press('Enter');
    await panel.waitForFunction(()=>document.querySelector('#state-label').textContent==='舞狮头');
    await panel.locator('#tab-programs').click();
    await panel.waitForFunction(()=>{const v=document.querySelector('#special-video');return !v.paused&&v.currentTime>.3;});
    await driver.open();
    await menu.getByRole('menuitem',{name:'小节目',exact:true}).hover();
    assert.equal(await menu.getByRole('menu',{name:'小节目',exact:true}).locator('button:not(:disabled)').count(),0);
    await app.evaluate(({BrowserWindow,screen})=>{const win=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('/pet.html')),area=screen.getPrimaryDisplay().workArea;win.setPosition(area.x+area.width-500,area.y+area.height-330);});
    await driver.open();
    await menu.getByRole('menuitem',{name:'小节目',exact:true}).hover();
    layout=await driver.geometry();
    assert.ok(layout.panels[1].x+layout.panels[1].width<=layout.panels[0].x,'submenu must flip left near the right edge');
    const finalArea=(await geometry()).area;
    assert.ok(layout.panels.every(p=>p.x>=finalArea.x&&p.y>=finalArea.y&&p.x+p.width<=finalArea.x+finalArea.width&&p.y+p.height<=finalArea.y+finalArea.height));
    await menu.screenshot({path:path.join(root,'out/pet-menu-left.png')});
    await menu.mouse.click(2,2);
    await panel.waitForTimeout(100);
    assert.equal((await driver.geometry()).visible,false,'clicking the transparent margin must dismiss the popup');
    await driver.open();
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('/index.html')).focus());
    await panel.waitForTimeout(100);
    assert.equal((await driver.geometry()).visible,false,'focusing another native window must dismiss the popup');
    // 通过实际拖动 IPC 验证越界；提醒与特效改变窗口尺寸时，人物锚点也不能被拉回工作区。
    await panel.evaluate(()=>window.whale.action('demo','idle'));
    async function dragTo(x,y) {
      const before=(await geometry()).bounds;
      await pet.evaluate(({dx,dy})=>{
        window.whale.drag('start',{x:200,y:200});
        window.whale.drag('move',{x:200+dx,y:200+dy});window.whale.drag('end');
      },{dx:x-before.x,dy:y-before.y});
      const actual=(await geometry()).bounds;
      assert.deepEqual({x:actual.x,y:actual.y},{x,y},'dragging must retain the chosen position outside the work area');
      return actual;
    }
    let free=await dragTo(finalArea.x-60,finalArea.y-60);
    await driver.open({x:130,y:140});
    assert.ok((await driver.geometry()).panels.every(p=>p.x>=finalArea.x&&p.y>=finalArea.y&&p.x+p.width<=finalArea.x+finalArea.width&&p.y+p.height<=finalArea.y+finalArea.height),'the menu must stay visible even when the pet is partly off-screen');
    await menu.keyboard.press('Escape');
    assert.deepEqual((await geometry()).bounds,free,'opening an edge-clamped menu must not pull the pet back');
    await panel.evaluate(()=>window.whale.action('fireworks'));
    const wide=(await geometry()).bounds;
    assert.equal(wide.width,340);
    assert.equal(wide.x+wide.width/2,free.x+free.width/2,'widening must preserve the off-screen horizontal anchor');
    assert.equal(wide.y+wide.height,free.y+free.height,'widening must preserve the off-screen foot position');
    await panel.evaluate(()=>window.whale.action('demo','idle'));
    await panel.evaluate(()=>window.whale.action('notifications',false));
    const event=spawnSync(process.execPath,[path.join(root,'scripts/codex-hook.cjs')],{env:{...process.env,WHALE_DATA_DIR:dir},
      input:JSON.stringify({hook_event_name:'Stop',session_id:'free-drag-check',turn_id:'drag-turn'}),encoding:'utf8'});
    assert.equal(event.status,0);
    await pet.waitForFunction(()=>document.querySelector('#unread-label').textContent==='已完成：1');
    const expanded=(await geometry()).bounds;
    assert.equal(expanded.height,380);
    assert.equal(expanded.y+expanded.height,free.y+free.height,'expanding reminders must preserve the foot position above the screen');
    assert.equal(expanded.x+expanded.width/2,free.x+free.width/2);
    free=await dragTo(finalArea.x+finalArea.width-80,finalArea.y+finalArea.height-80);
    assert.ok(free.x+free.width>finalArea.x+finalArea.width&&free.y+free.height>finalArea.y+finalArea.height,'right and bottom edges must not constrain the pet either');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({result:'passed',checks:['removed-scene-caption','three-categories','single-visible-page','compact-grid','keyboard-navigation','switch-preserves-state','emotion-action','custom-cascade-menu','fixed-pet-menu-anchor','left-dock-at-screen-edge','right-dock-after-moving','all-programs-retained','real-menu-program-playback','program-lock','submenu-flips-left','escape-and-blur-dismiss','pet-never-moves','free-drag-all-edges','off-screen-anchor-survives-resize'],screenshot:path.join(root,'out/pet-menu.png')}));
  } finally {await app.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
